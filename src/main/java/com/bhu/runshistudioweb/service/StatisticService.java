package com.bhu.runshistudioweb.service;

import com.bhu.runshistudioweb.model.vo.statistic.StatisticOverviewVO;

/**
 * 统计服务接口
 *
 * <p>本接口是首页大盘对调用方的契约，实现类只解释「为什么这么实现」。
 * 本模块刻意做得极小：只有一个方法、没有入参、没有写操作。
 *
 * <p>本期只提供一个「官网首页大盘」，因此只有 getOverview 一个方法。
 * 后续要做「按年份统计」「管理端运营看板」时，按同样套路在本接口加方法即可——
 * 统计类接口彼此独立，不要为了复用而把查询条件塞进一个万能方法里。
 * 一个万能方法会让每个调用方都要传一堆用不上的参数，也让「某个数字怎么算的」
 * 变成需要读条件分支才能回答的问题。
 *
 * <p>三条强制口径（实现类必须遵守）：
 * <ul>
 *     <li>一律排除逻辑删除的数据（deleted_at = 0）。这个条件由 MyBatis-Plus 的
 *     {@code @TableLogic} 自动追加，不写在代码里——它「看不见」，所以改统计口径时
 *     必须去 SQL 日志里确认它还在，否则统计会静默多算；</li>
 *     <li>出现枚举外的脏值（正常不会有，写入口已拦）→ 忽略不统计，不报错；</li>
 *     <li>空库或某维度为空时，返回完整的 key 集合且值为 0。</li>
 * </ul>
 * 第 2 条的理由：统计接口是首页的「锦上添花」，不该因为一条脏数据让整个首页挂掉；
 * 第 3 条的理由：前端图表按固定维度渲染，key 缺失会导致维度错乱或渲染报错。
 *
 * <p>为什么<b>不含成员人数</b>：本接口挂在匿名路径上，对外暴露「团队有多少人」
 * 同样属于展示成员信息，与「团队成员不对外展示」的规则冲突。
 * 管理端若需要人数统计，应另开一个要求 admin 的接口，而不是往这里加字段。
 *
 * @author shaoshing
 */
public interface StatisticService {

    /**
     * 查询官网首页大盘数据
     *
     * <p>为什么这样设计：首页是游客第一眼看到的页面，它必须在任何情况下都能渲染出来。
     * 因此本方法把「统计不出来」的所有情况都收敛成「0」而不是异常：
     * 空库、某维度没有数据、甚至某条记录的分组列是脏值，都不影响其余数字正常返回。
     * 这与业务接口的处理方式刚好相反——业务接口查不到数据要报 A0402，
     * 因为用户需要知道「你要的东西不存在」；而首页大盘没有数据就是「还没有数据」，
     * 报错只会让整个首页变成错误页。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 先算证书总数。这一步无附加条件，但逻辑删除条件仍会被自动追加，
     *     因此它统计的是「未删除的全部证书」；</li>
     *     <li>② 按级别分组统计，并按级别枚举把 key 全部预置为 0 再叠加真实计数——
     *     分组查询不会返回「0 条」的行，不补齐的话前端图表会缺维度；</li>
     *     <li>③ 按类型分组统计，同样补齐。两步各自独立，互不影响，
     *     任何一步出问题都不该拖垮另一部分。</li>
     * </ol>
     *
     * <p>容易踩的坑：两个分布的 key 集合由枚举决定，不是由数据库里的实际取值决定。
     * 因此「枚举里有、库里没有」的 key 会出现且为 0（正确），
     * 而「库里有、枚举里没有」的脏值会被<b>静默丢弃</b>（也是刻意的）。
     * 另一个坑是计数一律用 Integer 而不是 Long：项目全局把 Long 序列化成字符串
     * （为 19 位雪花 ID 让路），用 Long 存计数会让前端拿到 "12" 这样的字符串，
     * 排序与加法都会按字典序算。
     *
     * <p>本方法匿名可访问、无任何入参、无副作用、无写库，
     * 因此重复调用完全幂等（重复调用结果一致，只要期间数据没变）。
     *
     * @return 大盘统计，永不为 null；空库时返回全 0 且两个分布的 key 集合完整
     *         （key 顺序与枚举声明顺序一致，前端图例顺序因此稳定）
     */
    StatisticOverviewVO getOverview();
}
