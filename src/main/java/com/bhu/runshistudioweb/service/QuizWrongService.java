package com.bhu.runshistudioweb.service;

import com.baomidou.mybatisplus.extension.plugins.pagination.Page;
import com.baomidou.mybatisplus.spring.service.IService;
import com.bhu.runshistudioweb.model.dto.quiz.QuizWrongQueryRequest;
import com.bhu.runshistudioweb.model.entity.StudioQuizWrong;
import com.bhu.runshistudioweb.model.vo.quiz.QuizWrongDetailVO;
import com.bhu.runshistudioweb.model.vo.quiz.QuizWrongItemVO;

/**
 * 刷题错题本服务
 *
 * <p>本接口是错题本对调用方的契约，实现类只解释「为什么这么实现」。
 *
 * <p>本服务只被一个地方调用：QuizPracticeServiceImpl 在判分之后
 * 调 applyOutcome。这是刻意的——错题本的状态迁移必须只有一个写入口，
 * 否则「答对时该加连对还是直接消解」这类规则会散落在多处，
 * 迟早出现「答题页的判定说已消解、错题本页还显示待复习」的不一致，
 * 而这种不一致不会报错，只能靠用户投诉发现。
 *
 * <p>状态机（唯一的迁移表，改规则只改这里）：
 * <pre>
 * 事件   | 条目不存在                        | 条目存在
 * 答错   | 插入 status=0, wrongCount=1,      | status→0, wrongCount+1,
 *        | streak=0                          | streak=0, 清空 resolvedAt
 * 答对   | 不动作                            | 待复习：streak+1；达阈值 → status=1
 * 跳过   | 完全不调用本方法（「跳过不记错」） |
 * </pre>
 *
 * <p>题目被停用 / 删除时本表不动：过滤发生在查询侧（子查询），
 * 这样停用是可逆的——重新启用后条目自动回来。若改成「停用时删条目」，
 * 重新启用后用户的错题记录就永久消失了。
 *
 * <p>约定：参数不合法 / 越权时抛 BusinessException，不返回 null。
 * 注意本接口<b>不做</b>成员校验：它被刷题服务在内部调用，
 * 准入在那一层已经校验过；只有 C 端入口（错题列表 / 详情 / 标记掌握）
 * 需要在 Controller 里取当前登录用户 ID 再传进来。
 *
 * @author shaoshing
 */
public interface QuizWrongService extends IService<StudioQuizWrong> {

    /**
     * 按一次作答结果更新错题本（状态机的唯一写入口）
     *
     * <p>为什么这样设计：错题本是一个状态机——答错加入待复习、在错题本里答对累加连对、
     * 连对达到阈值才消解、已消解的题再答错回到待复习。这些迁移必须只有一个写入口，
     * 否则「提交作答」与「手动标记已掌握」两条入口各写一套规则，
     * 迟早出现两处结论不一致。因此本方法被设计成「进来一次，出结果一次」：
     * 先查一次当前条目，再按对错分成两条支路，两支都只改这一条记录。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 先按「用户 + 题目」查已有条目。这个查询必须发生在任何写操作之前，
     *     因为「首次入本」与「再错一次」的落库方式不同（insert 还是 update）；</li>
     *     <li>② 答错：区分「条目不存在」与「条目已存在」，两者的落库规则一致，
     *     只有返回给前端的动作类型不同；</li>
     *     <li>③ 答对：只推进连对进度，绝不为「从没做错过的题」建条目——
     *     那会把「已消解」的含义变成「做对过的题数」。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法带事务，但它做的是「读一次 + 写一次」，并没有行锁保护。
     * 同一用户对同一题并发提交两次时，两个线程可能都查到「条目不存在」然后都去 insert，
     * 撞唯一键的那一个会抛异常回滚。真正拦住重复提交的是作答表上的唯一键，
     * 这里不重复做那层防护——错题本的写入总是跟在「作答记录插入成功」之后。
     * 另一个坑是错误次数用「读出来 +1 再写回」而不是 SQL 里的自增表达式，
     * 并发时会丢一次计数；同样由作答表的唯一键兜住，但这个前提不能忘。
     *
     * @param userId 用户 ID，必须是当前登录且在队的成员（准入由调用方校验，本方法不查成员表）
     * @param questionId 题目 ID，必须是调用方刚刚判过分的题；传错只会写脏一条错题记录，
     *                   不会报错，也不会影响别人的数据
     * @param correct 本次是否答对；答错会累加错误次数并把连对清零，
     *                已消解的条目会被打回待复习
     * @param resolveStreak 消解阈值（连续答对几次算掌握），小于 1 时按 1 处理——
     *                      配置成 0 会让第一次答对就消解，虽然不报错但语义明显不对
     * @return 本次对错题本的影响，取值见 QuizVerdictVO#wrongBookAction
     *         （added / reopened / progress / resolved / none）；
     *         永不为 null，调用方不必判空
     */
    Outcome applyOutcome(long userId, long questionId, boolean correct, int resolveStreak);

    /**
     * 我的错题本分页
     *
     * <p>为什么这样设计：列表与计数必须用同一套过滤条件，否则会出现
     * 「概览显示 9 条待复习、点进去只有 7 条」这种自相矛盾的界面，而它不会报错，
     * 只会让用户觉得数据不可信。因此「只列待复习」与「过滤掉已停用 / 已删除的题目」
     * 这两个条件，在列表、计数、错题重刷候选池三处完全一致。
     *
     * <p>按教材 / 章节筛选时「先查题目 ID 再用 IN 过滤」而不是 JOIN：
     * 本项目不手写 SQL，而错题量在几十到几百的量级，两次查询完全够用。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 请求为 null 时兜一个空对象，下面就不必到处判空；</li>
     *     <li>② 拼基础条件：用户、待复习状态、题目可见性、排序。
     *     排序按「最久没复习」升序——错题本的价值在于把忘掉的捡回来，
     *     而不是反复刷最近刚错的那道；</li>
     *     <li>③ 范围筛选：先查范围内题目 ID，为空则直接返回空页。
     *     这一步不能省，否则会带着一个空 IN 条件去查库；</li>
     *     <li>④ 分页查询实体，分页参数走兜底纠正，不因页码非法而报错；</li>
     *     <li>⑤ 实体转 VO，题目信息一次批量查完，避免逐行查题目的 N+1；</li>
     *     <li>⑥ 组装 VO 分页对象，必须把 current / size / total 一并带过去，
     *     否则前端的分页控件会显示成「第 1 页、共 0 条」。</li>
     * </ol>
     *
     * <p>容易踩的坑：列表<b>不含答案</b>。浏览列表时并没有「我要复盘这一题」的意图，
     * 在列表里泄露答案就变成了作弊捷径——答案只在详情接口里给。
     * 另一个坑是 total 是「过滤后」的总数，正常情况下与 records 长度口径一致，
     * 但极端情况下（题目被删除而条目还没来得及清理）records 可能少于 total，
     * 这不是 bug，跳过缺失条目只是防御性写法。
     *
     * @param userId 用户 ID，必须是当前登录用户；本方法<b>不校验归属</b>，
     *               调用方负责传入自己的 ID，传错会读到别人的错题本
     * @param request 查询条件（教材名 / 章节名 / 分页参数），允许为 null
     * @return 分页结果，记录不含答案；没有待复习条目时返回空页
     *         （records 为空列表、total 为 0），不返回 null
     */
    Page<QuizWrongItemVO> listMyWrongByPage(long userId, QuizWrongQueryRequest request);

    /**
     * 错题详情（含答案与解析）
     *
     * <p>为什么这样设计：能进错题本的前提是「这道题你做错过」，
     * 做错过的人看到答案是应该的，藏着反而让他无法复盘。
     * 但列表不带答案（见 listMyWrongByPage）——浏览列表时并没有复盘意图。
     * 另一个细节是「不存在」与「不属于本人」返回<b>同一个错误</b>：
     * 如果分开报错，别人就能靠错误码枚举出「哪些 ID 是真实存在的」。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 先校验 id 为正：负数与 0 不可能存在，早点拒绝省一次查询；</li>
     *     <li>② 查条目并校验归属。归属判断必须紧跟查询，不能等到组装 VO 之后——
     *     越早拒绝，后面的代码就越不需要考虑越权；</li>
     *     <li>③ 查题目本体。题目可能已被删除，此时给「题目已被删除」而不是
     *     「无权访问」，避免用户以为是权限问题；</li>
     *     <li>④ 先填公共字段（题干、教材章节、次数、时间），再补只有详情才有的
     *     选项、正确答案与解析；</li>
     *     <li>⑤ 「上次所选」要单独查作答表：错题条目本身只记状态，不记用户当时选了什么。</li>
     * </ol>
     *
     * <p>容易踩的坑：正确答案取的是题目表里的<b>当前值</b>，不是作答记录里的快照。
     * 管理员改过答案后，这里显示新答案，而作答记录里存的是提交时的旧答案——
     * 复盘时两者可能对不上。这是刻意的取舍：详情页要回答「正确答案是什么」，
     * 而不是「当时系统认为的正确答案是什么」。
     *
     * @param userId 当前登录用户 ID，用于归属校验；不是本人的条目一律按「不存在」处理
     * @param id 错题本条目 ID（<b>不是</b>题目 ID）；小于等于 0 时抛 A0401
     * @return 错题详情，含选项、正确答案、解析与上次所选；
     *         lastChosenLabels 在没有答错记录时为 null，前端需判空
     * @throws com.bhu.runshistudioweb.exception.BusinessException id 非法时抛 A0401；
     *         条目不存在或不属于当前用户时抛 A0301；题目已被删除时抛 A0402
     */
    QuizWrongDetailVO getMyWrongDetail(long userId, long id);

    /**
     * 手动「标记已掌握」
     *
     * <p>为什么这样设计：自动消解要求连续答对若干次，但用户可能已经通过别的材料
     * 掌握了这道题，不想再刷几遍才能让它从错题本里消失。手动入口就是给这种情况留的，
     * 它跳过连对计数，直接把状态置为已消解。
     *
     * <p>幂等（重复调用结果一致）：已消解时直接返回 true，且<b>不改 resolvedAt</b>——
     * 重复点击不该把「什么时候掌握的」这个时间点改掉，否则用户每点一次这个时间就往后跳，
     * 错题本的时间线就失去了意义。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 校验 id 为正，与详情接口保持同一套入参校验；</li>
     *     <li>② 查条目并校验归属。不查归属就能改别人的错题本，
     *     这是越权，必须在写操作之前拦住；</li>
     *     <li>③ 已消解直接返回 true：幂等的落点，不写库、不改时间；</li>
     *     <li>④ 未消解才更新，同时写状态、消解时间与消解方式
     *     （记为「手动」，与自动消解区分开，便于事后统计）。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法没有事务注解。它只写一行、且没有任何跨表联动，
     * 加事务只会多一层代理开销；但若将来要在标记掌握时顺带清理别的东西，
     * 就必须补上事务，否则会出现「错题本消解了、关联数据没清」的半成品状态。
     * 另一个坑是返回值直接透传更新结果，false 表示该行已不存在——
     * 而存在性在第 ② 步已经校验过，因此 false 只可能是并发删除。
     *
     * @param userId 当前登录用户 ID，用于归属校验
     * @param id 错题本条目 ID（<b>不是</b>题目 ID）；小于等于 0 时抛 A0401
     * @return true 表示成功，包含「本来就已经消解」的情况；false 表示更新未生效
     * @throws com.bhu.runshistudioweb.exception.BusinessException id 非法时抛 A0401；
     *         条目不存在或不属于当前用户时抛 A0301
     */
    boolean resolveManually(long userId, long id);

    /**
     * 待复习错题数（学习概览用）
     *
     * <p>为什么这样设计：这个数字必须和错题本列表的条数完全一致，否则用户会看到
     * 「概览说 9 条待复习、点进去只有 7 条」这种自相矛盾的界面。
     * 因此这里用的过滤条件与 listMyWrongByPage 完全相同，连「题目可见」的子查询
     * 都是同一份定义——两处各写一份，改一处漏一处就会立刻出现上面那种不一致，
     * 而且它不会报错。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 按用户 + 待复习状态计数，再叠加题目可见性过滤。
     *     三个条件缺一不可：少用户条件会统计到别人的错题，少状态条件会把已消解的算进来，
     *     少可见性条件会把已停用 / 已删除的题也算进来；</li>
     *     <li>② 转成 int 返回。概览接口的字段是 int，转换失败会抛异常而不是静默截断——
     *     条数理论上不会溢出，但真溢出时抛出来比悄悄变成负数更容易发现。</li>
     * </ol>
     *
     * <p>容易踩的坑：统计的是「条目数」而不是「题目数」。同一用户对一道题只有一条记录
     * （由「用户 + 题目」唯一键保证），所以两者恰好相等；若将来允许多条，
     * 这个数字的含义就要重新定义。另外待复习数与已消解数相加<b>不一定</b>等于总条目数，
     * 因为停用题目的条目两边都不计。
     *
     * @param userId 用户 ID；传错会统计到别人的数据，调用方必须传当前登录用户
     * @return 待复习条目数；没有错题时返回 0（不是 null）
     */
    int countPending(long userId);

    /**
     * 已消解错题数（学习概览用）
     *
     * <p>为什么这样设计：这个数字的口径是「当前状态」，不是「历史累计」。
     * 一道已消解的题如果又被答错，它会回到待复习，这个数字就应该减 1。
     * 若按历史累计来算，它会只增不减，对用户没有任何行动指引——
     * 「你已经掌握了 37 题」听起来不错，但其中可能有 10 题又忘光了。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 按用户 + 已消解状态计数，并叠加与待复习数完全相同的可见性过滤。
     *     停用的题不显示，但条目本身保留，重新启用后会自动回到这个数字里；</li>
     *     <li>② 转成 int 返回，溢出时抛异常而不是静默截断。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法与 countPending 必须用同一套可见性口径，
     * 否则两个数字加起来会对不上，用户会以为系统漏了数据。
     * 这也是为什么两处共用一个子查询常量，而不是各写一遍。
     *
     * @param userId 用户 ID；调用方必须传当前登录用户
     * @return 已消解条目数（按当前状态统计）；没有时返回 0（不是 null）
     */
    int countResolved(long userId);

    /**
     * 取待复习的题目 ID（错题重刷的候选池，按「最久没复习」排序）
     *
     * <p>为什么这样设计：错题重刷模式的候选池必须与顺序模式严格区分开——
     * 顺序模式排除「已作答」的题，错题模式只出「待复习」的题，两个集合不重叠，
     * 用户才不会在两个入口看到同一批题。因此本方法只认待复习状态，
     * 并且同样过滤掉停用与删除的题目，否则会抽出一批点进去没有内容的题。
     *
     * <p>排序按「最久没复习」升序：错题本的价值在于「隔一段时间再考一次」，
     * 总是先出最近刚错的那几道等于没复习。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 只查题目 ID 一列并排好序：候选池只用来挑题，不需要题目内容；</li>
     *     <li>② 空结果直接返回空列表，调用方只需判 isEmpty；</li>
     *     <li>③ 没有任何范围条件时直接返回，省掉一次「查范围内题目」的查询——
     *     这是「不限教材章节」的常见路径；</li>
     *     <li>④ 有范围条件时先查范围内题目 ID，再按原顺序过滤保留。
     *     不能反过来「先按范围查题目、再与错题取交集」，那会丢掉「最久没复习」的排序。</li>
     * </ol>
     *
     * <p>容易踩的坑：范围过滤用的是列表的 contains，范围题量大时是 O(n²)。
     * 这里没有改成集合，是因为一次错题重刷的候选量由题量配置封顶（几十条），
     * 而「保留原顺序」比这点开销重要得多。另一个坑是参数传空串与传 null 不等价：
     * 本方法只把 null 当作「不限」，空串会被拼成「章节名 = 空串」的条件，
     * 调用方必须先做 trim 与空值归一。
     *
     * @param userId 用户 ID；调用方必须传当前登录用户
     * @param textbookName 教材名称，为 null 表示不限；空串应按 null 处理，由调用方归一
     * @param chapterName 章节名称，为 null 表示不限；
     *                    只传章节不传教材在语义上无法定位，调用方需先校验
     * @return 题目 ID 列表，按「最久没复习」升序；没有待复习题时返回空列表（不是 null）
     */
    java.util.List<Long> listPendingQuestionIds(long userId, String textbookName, String chapterName);

    /**
     * 本次作答对错题本的影响
     *
     * <p>为什么这样设计：调用方需要同时拿到「发生了什么」与「还差几次消解」——
     * 前者决定提示文案（已加入 / 又回来了 / 已消解），后者决定「再答对 N 次即掌握」的进度提示。
     * 只返回字符串会让后者无处安放，只返回数字又分不清是「首次入本」还是「打回待复习」。
     *
     * <p>用 record 而不是普通类：它是纯粹的数据载体，没有行为、不该被继承，
     * 也不需要 setter。record 天然不可变，避免调用方拿到结果后又把它改掉。
     *
     * <p>容易踩的坑：remainingStreak 只在 progress 时非 null，其余情况为 null——
     * 但 resolved 时实现里给的是 0 而不是 null。因此前端判断「要不要显示进度提示」
     * 必须看 action 而不是看这个数字是否为 null，否则刚消解时会显示「再答对 0 次」。
     *
     * @param action 影响类型，直接对应 QuizVerdictVO#wrongBookAction：
     *               added（首次入本）/ reopened（已消解又答错）/ progress（连对未达标）/
     *               resolved（本次消解）/ none（无副作用）；永不为 null
     * @param remainingStreak 还差几次消解，仅 action 为 progress 时有意义；
     *                        其余情况为 null（resolved 时为 0），前端需按 action 判断
     */
    record Outcome(String action, Integer remainingStreak) {
    }
}
