/**
 * 知识库文档服务（RAG 入库与检索的编排中枢）
 *
 * <p>一句话职责：把「一段正文」变成「1 行文档 + N 行切分块 + N 个向量」，
 * 并且做到幂等（重复调用结果一致）、可重建、失败可重试。
 * 所谓「切分块」是把长正文按 500 字左右切开后的一小段，向量则是对应每一段算出的
 * 一串浮点数，用来算「问题与这段文字有多像」。
 *
 * <p>方法按用途分四组，读代码时按这个分层找：
 * <ul>
 *     <li>入库：ingestManual、sync——把正文变成文档与向量；</li>
 *     <li>检索：retrieve——供问答链路调用，返回「拼好的资料文本 + 溯源列表」；</li>
 *     <li>管理端：syncAll、listDocByPage、deleteDoc、rebuildDoc；</li>
 *     <li>向量重建：reindexAll——向量库是进程内内存，重启后靠它恢复。</li>
 * </ul>
 *
 * <p>两个入库入口不要合并：ingestManual 是手工录入，每次新建、不幂等——
 * 它没有业务主键，拿什么判断「这是同一篇」？sync 是业务来源同步，幂等——
 * 靠 (sourceType, sourceId) 这一对定位文档，再比对内容哈希决定「跳过」还是「重建」。
 *
 * <p>本模块最重要的一条事务纪律：外部 HTTP（向量化）绝不能包在数据库事务里，
 * 而「写文档行 + 逻辑删旧块 + 插入新块」三处必须同在一个事务内。
 * 前者会让数据库连接被一次十几秒的调用占住，后者不同事务就会出现
 * 「旧块已删、新块没插完」的空窗，那段时间这篇文档检索不到。
 *
 * @author shaoshing
 */
public interface KnowledgeDocService {

    /**
     * 手工录入一篇文档：每次都新建，不参与幂等
     *
     * <p>为什么这样设计：手工录入的正文没有业务主键（它不对应 project / member 等
     * 任何一行业务数据），因此无法判断「这次提交和上次是不是同一篇」。
     * 强行用标题做去重是错的——两篇同名的《使用说明》是完全合法的。
     * 所以这里选择「每次调用都新建一篇」，把「要不要重复录入」的判断交给人。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 校验请求体与标题 / 正文：空标题、空正文、正文超过 20000 字都返回 A0401。
     *     放在最前面，是为了让后面的切分与向量化不会为一个必然失败的请求花钱；</li>
     *     <li>② 复用与 sync 相同的入库主流程（切分 → 向量化 → 事务落库），
     *     但来源类型固定为 manual、来源 ID 传 null。复用同一段代码而不是另写一套，
     *     才能保证「手工录入」与「业务同步」在切块、向量、状态上口径一致；</li>
     *     <li>③ 返回入库结果：切出几块、状态是否为已索引。
     *     状态是 1 说明块与向量都已就位，检索立刻能命中。</li>
     * </ol>
     *
     * <p>容易踩的坑：正文长度上限有两道校验（DTO 上的 {@code @Size} 与 Service 里的常量），
     * 缺一不可——注解只在 Web 入口生效，若这个方法被定时任务或测试直接调用，注解不会执行。
     * 另外「纯空格」的正文必须在 trim 之后判空，否则它会通过「非 null」的检查，
     * 切出一个内容全是空白的块，白白产生一次向量化费用。
     *
     * @param request 录入请求：title 与 content 均必填，正文不超过 20000 字；
     *                整个对象为 null 时得到 A0401
     * @return 入库结果：docId、标题、切分块数、状态（1 已索引）、skipped 恒为 false
     *         （手工录入从不跳过）
     * @throws com.bhu.runshistudioweb.exception.BusinessException 参数不合法（A0401）、
     * 向量化失败（C0200）、数据库写入影响行数不为 1（B0002）时抛出
     */
    KnowledgeIngestVO ingestManual(KnowledgeManualIngestRequest request);

    /**
     * 把一条业务数据（项目 / 成员 / 证书）同步进知识库：幂等、可重建
     *
     * <p>为什么这样设计：同一个业务主键（例如某个项目）在知识库里只应有一篇文档，
     * 所以这里用 (sourceType, sourceId) 定位，再比对正文的 SHA-256 摘要（内容哈希，
     * 同一段文本必然算出同一个 64 位十六进制串，改一个字就会变）：
     * 哈希没变且文档已是「已索引」状态时直接返回 skipped=true，不调用 Embedding、
     * 不写库——幂等省下的不只是时间，Embedding 是按文本量计费的，跳过就是省钱。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 校验来源类型与来源 ID：类型必须落在 project / member / certificate 里，
     *     传 manual 直接 A0401（manual 没有业务来源，走这个入口无法幂等）；</li>
     *     <li>② 读业务源并拼正文：源数据不存在时把已有文档标记为失败态再抛 A0402。
     *     这一步必须排在幂等判定之前，因为「内容有没有变」只有读到源才能算；</li>
     *     <li>③ 幂等判定：算哈希、查已有文档，只有「哈希相同」且「状态为已索引」
     *     两个条件同时成立才跳过；</li>
     *     <li>④ 进入入库主流程：内容变了，或状态不是已索引，都要重建一次。
     *     重建时旧块在事务内逻辑删除、新块插入、旧向量在提交后清理。</li>
     * </ol>
     *
     * <p>容易踩的坑：幂等判断不能只比哈希，必须同时要求「状态是已索引」。
     * 失败（status=2）的文档不会写入新哈希，于是「源恢复且内容未变」时会命中
     * 「哈希相同 → 跳过」，状态就永远停在失败态，这篇文档再也修不回来。
     * 另一个坑是「先删旧块再向量化」——那样一次 Embedding 故障就会让文档彻底查不到；
     * 正确顺序是「先备好新材料，再在事务里原子替换」。
     *
     * @param request 同步请求：sourceType ∈ project / member / certificate（大小写敏感），
     *                sourceId 必须是正整数；两者任一不合法都得到 A0401
     * @return 入库结果：skipped=true 表示内容未变、什么都没做；
     *         rebuilt=true 表示替换了旧块；两者都为 false 表示首次新建
     * @throws com.bhu.runshistudioweb.exception.BusinessException 参数不合法或传了 manual（A0401）、
     * 源数据不存在（A0402，同时把已有文档标记为失败态）、向量化失败（C0200）时抛出
     */
    KnowledgeIngestVO sync(KnowledgeSyncRequest request);

    // ==================== 检索 ====================

    /**
     * 检索与问题相关的资料，返回「拼好的资料文本 + 溯源列表」
     *
     * <p>为什么这样设计：这是内部编排方法而不是对外接口——它由问答链路调用，
     * 因此失败时抛异常而不是自己吞掉。「检索失败能不能继续聊天」是问答链路的策略，
     * 不该写死在这里：同步与流式两条路径都选择降级为「无资料」，但那是调用方的决定。
     * 检索固定只走 2 条 SQL：一条按向量 ID 批量回查切分块、一条按文档 ID 批量回查文档。
     * 命中 5 条也只查这两次，绝不在循环里逐条回查——那是最典型的 N+1 查询。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 问题向量化 + 向量检索：问题先用与入库完全相同的向量模型算成向量，
     *     再在向量库里找相似度最高的 topK 条。这一步纯内存，没有 SQL。
     *     它必须最先做——没有命中就没有后续的回查；</li>
     *     <li>② 按 embedding_id 批量回查切分块：向量库里只存了向量与块正文，
     *     「这块属于哪篇文档」只在数据库里，所以要按 ID 回查一次；</li>
     *     <li>③ 按 doc_id 批量回查文档：溯源要展示标题与来源，这些字段只在文档行上；</li>
     *     <li>④ 按相似度降序组装资料文本与溯源列表：遍历的是向量检索给出的命中顺序，
     *     不是回查结果——回查结果是个集合，顺序没有意义，而模型对「最相关的资料放最前」
     *     很敏感，顺序被打乱会明显降低回答质量。</li>
     * </ol>
     *
     * <p>容易踩的坑：回查为空必须跳过而不是报错。向量库的清理是尽力而为的
     * （删文档时若清理失败，向量库里会残留条目），所以「命中一条向量、回查却查不到块」
     * 是正常现象。一条脏数据不该让整次提问失败。另外用 Map 收集回查结果时要提供
     * 合并函数，否则同一个 key 出现两次会让收集动作抛异常，把整次提问打断。
     *
     * @param question 用户提问；为空或纯空白时直接返回空结果，不会抛异常
     * @return 检索结果：无命中时 contextText 是空串、sources 是空列表，两者都不为 null，
     *         调用方用 hit() 判断有没有命中即可
     * @throws com.bhu.runshistudioweb.exception.BusinessException 问题向量化失败（C0200）时抛出；
     *         是否捕获由调用方决定（问答链路会捕获并降级）
     */
    RetrievalResult retrieve(String question);

    // ==================== 管理端操作 ====================

    /**
     * 全量同步：把三类业务数据（未删除的项目 / 成员 / 证书）一次性灌进知识库
     *
     * <p>为什么这样设计：它本质就是「N 次幂等 sync 的循环」，因此可以放心重跑——
     * 内容没变的会被幂等跳过（零 Embedding、零写库），跑第二遍的代价接近 0。
     * 刻意不包进一个大事务：每条 sync 自己是一个事务，单条失败只回滚那一条，
     * 其余继续。包大事务既会让向量化期间长时间占着连接，又会把「50 条成功、1 条失败」
     * 变成「51 条全回滚」——而失败的那条下次重跑就能补上。
     * 也刻意不做「批量向量化」优化：一次 sync-all 的耗时主要在 Embedding，
     * 而计费按文本量而非请求数，把请求攒成一批只能减少往返次数，
     * 却要重写「块与向量 ID 一一对应」的装配逻辑，收益与风险不成比例。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 三类源各查一次 ID 列表，只 select 主键、不把正文拉回内存。
     *     正文由每条 sync 自己按需读，避免一次把几十篇长文读进堆内存；</li>
     *     <li>② 逐条走 sync，把结果累加进计数器（总数 / 新建 / 重建 / 跳过 / 失败）。
     *     单条失败只累计不中断：一条项目正文太长导致向量化失败，
     *     不该让另外 50 条成员档案也跟着进不去；</li>
     *     <li>③ 返回统计。五个数字互斥且完备：
     *     created + rebuilt + skipped + failed 一定等于 total。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法返回统计而不是抛异常，所以「全部失败」也会是 HTTP 200 +
     * 一份 failed=51 的统计。调用方（管理端页面）必须看 failed 字段，
     * 不能只看「接口没报错」就以为同步成功。
     *
     * @return 统计结果：total / created / rebuilt / skipped / failed；
     *         库里三类数据都为空时 total 为 0，其余字段也都是 0
     */
    KnowledgeSyncAllVO syncAll();

    /**
     * 强制重建全部文档的向量（向量库的恢复手段）
     *
     * <p>为什么这样设计：恢复向量不需要读业务源、也不需要重新切分——向量化的输入
     * 本来就是切分块表里已经存在的文本。所以「重新嵌入现有切分块」就够了，
     * 而且对「手工录入」与「业务来源同步」两类文档一视同仁：手工录入的文档没有业务源，
     * 靠 syncAll 是恢复不了的，只有这条路径能救回它的向量。
     * 什么时候必须用它：向量库是进程内内存，应用每次重启，切分块行还在但向量全没了；
     * 此时 syncAll 会因为内容哈希未变而全部 skipped（什么都不会做），
     * 检索命中 0 条，只有本方法能恢复。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 一条 SQL 取全部未删除文档的主键（正文在切分块行里，这里不需要）；</li>
     *     <li>② 逐文档重建：读该文档的存活块 → 重新向量化（外部 HTTP，事务外）
     *     → 事务内把新的向量 ID 写回各块 → 提交后清理旧向量。
     *     每条独立事务、单条失败不中断，与 syncAll 同一风格；</li>
     *     <li>③ 返回统计。本方法不新建任何文档，因此 created 恒为 0。</li>
     * </ol>
     *
     * <p>容易踩的坑：不要指望 syncAll 能替代它。syncAll 的幂等判定是「哈希没变就跳过」，
     * 而重启后哈希确实没变，于是它一条都不会重建——看起来接口成功、检索却始终为空，
     * 这是本模块最容易误判的故障。
     *
     * @return 统计：rebuilt 是成功重建向量的文档数，skipped 是没有可用切分块而跳过的文档数，
     *         failed 是失败数；没有文档时三项都是 0
     */
    KnowledgeSyncAllVO reindexAll();

    /**
     * 管理端分页查询文档列表（不含正文）
     *
     * <p>为什么这样设计：正文不在文档行里（它已经切分进块表），拼回来再返回意味着一页
     * 10 条要读几百行块。这个接口只回答「有哪些文档、各自什么状态」，
     * 管理员据此决定删除还是重建，不需要看到正文。
     * 来源类型是闭集（只允许四个固定取值），传了约定外的值必须报错而不是静默返回空列表——
     * 否则管理员会以为「库里没有这类文档」，排查方向被彻底带偏。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 归一化请求对象与分页参数：null 按第一页 10 条处理，每页条数上限 50，
     *     防止一个 pageSize=100000 把整张表读进内存；</li>
     *     <li>② 校验来源类型：非空时必须能映射到枚举，否则 A0401；</li>
     *     <li>③ 组装条件：标题模糊匹配、来源类型与状态精确匹配，三个条件都只在
     *     「有传值」时才生效——不加这个判断，不传来源类型时会变成
     *     {@code source_type = null}，一条都查不出来；</li>
     *     <li>④ 按创建时间倒序 + id 倒序分页查询并转 VO。
     *     次级排序键必须是 id：创建时间只有秒级精度，同一秒入库的文档会并列。</li>
     * </ol>
     *
     * <p>容易踩的坑：条件构造里的「是否拼接」开关必须与参数判空成对出现。
     * 把 {@code like} 的布尔开关写成常量 true，空标题就会拼出 {@code title LIKE '%%'}，
     * 虽然结果碰巧正确，但会白白多一个用不上索引的条件。
     *
     * @param request 查询条件（title 模糊 / sourceType 精确 / status 精确 + 分页参数），
     *                允许为 null，此时按第一页 10 条返回
     * @return 分页结果，记录为 KnowledgeDocVO（不含正文）；没有数据时 records 为空列表
     * @throws com.bhu.runshistudioweb.exception.BusinessException 来源类型取值非法时抛出（A0401）
     */
    Page<KnowledgeDocVO> listDocByPage(KnowledgeDocQueryRequest request);

    /**
     * 删除文档：逻辑删文档 + 同事务级联逻辑删切分块，提交后尽力清理向量
     *
     * <p>为什么这样设计：数据库里只做「标记删除」（把 deleted_at 写成毫秒时间戳），
     * 因此文档与切分块必须在同一个事务里一起标记——只删文档会留下
     * 「块还在、文档没了」的孤儿行，它们虽然不会出现在检索结果里（文档反查为空会被跳过），
     * 但会一直占着行与向量。向量清理放在事务提交之后，因为它是内存操作、无法回滚，
     * 放进事务里只是「假装」参与原子性。
     * 为什么必须清向量：检索层对「回查为空」的容忍只是兜底。不清理的话，
     * 这些悬挂命中会长期占用 topK 名额（5 条结果里混进 3 条已删文档的块），
     * 表现为「检索结果变少、相关性下降」，而且没有任何报错。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 校验 ID 并查文档是否存在：不存在直接 A0402。
     *     先查一次而不是直接删，是为了区分「不存在」与「删除失败」——
     *     直接删只会得到影响行数 0，无法告诉调用方到底哪种情况；</li>
     *     <li>② 删除前先把向量 ID 取出来：块被逻辑删除后查询会自动过滤，
     *     事后再也拿不到这些 ID，向量就永远清不掉了；</li>
     *     <li>③ 事务内标记删除文档与全部切分块：两者同生共死；</li>
     *     <li>④ 提交后清理向量：尽力而为，失败只告警（残留向量在应用重启后自然消失）。</li>
     * </ol>
     *
     * <p>容易踩的坑：向量 ID 必须在删除前取。若写成「先删库、再查向量 ID」，
     * 查询会因逻辑删除条件而返回空列表，清理动作变成空转——而且完全不报错。
     *
     * @param id 文档 ID；小于等于 0 时得到 A0401
     * @return 恒为 true。删除不成功一律抛异常，没有「返回 false 表示失败」的分支
     * @throws com.bhu.runshistudioweb.exception.BusinessException 参数非法（A0401）、
     * 文档不存在或已删除（A0402）、删除影响行数不为 1（B0002）时抛出
     */
    boolean deleteDoc(long id);

    /**
     * 重建一篇文档：回到业务源重新读一遍正文，重新切分与向量化
     *
     * <p>为什么这样设计：重建必须回业务源读，不能从切分块拼回正文——
     * 拼回来会丢失原来的切分边界，再切一次得到的块与原来不同，
     * 相当于用一份被自己加工过的二手文本重新入库。手工录入的文档没有业务源可回读，
     * 因此明确拒绝（A0401）并引导到「删除后重新录入」，而不是静默拼接。
     * 内容没变时返回 skipped=true，此时没有产生任何 Embedding 调用。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 校验 ID 并查文档：不存在 A0402；</li>
     *     <li>② 拒绝手工录入来源：manual 没有业务源，重建无从谈起。
     *     这个判断必须排在调用 sync 之前，否则会带着 null 来源 ID 进去，
     *     报出一个与真实原因无关的错误；</li>
     *     <li>③ 校验来源 ID 非空，然后直接复用 sync：读源 → 比对哈希 → 未变则跳过、
     *     变了则重建。复用而不是另写一套，才能保证「重建」与「同步」行为完全一致。</li>
     * </ol>
     *
     * <p>容易踩的坑：不要以为「重建」一定会真的重建。它是幂等的：
     * 源内容与库里一致时返回 skipped=true，管理员点了一次却什么都没发生——
     * 这是正确行为，前端需要把 skipped 如实展示出来，否则会被当成接口失效。
     *
     * @param id 文档 ID；小于等于 0 时得到 A0401
     * @return 入库结果：skipped=true 表示内容未变、本次零 Embedding 调用；
     *         rebuilt=true 表示旧块已被替换
     * @throws com.bhu.runshistudioweb.exception.BusinessException 参数非法或文档不存在（A0401 / A0402）、
     * manual 来源不支持重建（A0401）、源数据已删除（A0402）时抛出
     */
    KnowledgeIngestVO rebuildDoc(long id);

    /**
     * 检索结果：拼给模型读的资料文本 + 给前端展示的溯源列表
     *
     * <p>为什么这样设计：定义为接口内的嵌套 record（不可变数据载体，编译器自动生成
     * 构造器与访问器）而不是单独建一个文件——它只在本接口的检索场景里出现，
     * 单独建文件反而增加一层跳转，还容易被误当成对外 VO 拿去复用。
     *
     * <p>容易踩的坑：两个字段的消费方完全不同。contextText 只给模型读，
     * 不对外返回（它可能很长）；sources 才给前端展示。若把 contextText 也塞进响应，
     * 一次回答会平白多出几 KB 的正文。
     *
     * @param contextText 拼好的资料文本（带序号、标题与来源标注），供模型阅读；
     *                    无命中时是空串而不是 null
     * @param sources 溯源列表，供前端展示「这条回答参考了哪些资料」；
     *                无命中时是空列表而不是 null
     */
    record RetrievalResult(String contextText, List<KnowledgeSourceVO> sources) {

        /**
         * 空结果：无命中、或入参为空时返回它，避免调用方到处判 null
         *
         * <p>为什么这样设计：问答链路的降级分支（检索失败、熔断跳过）都需要一个
         * 「什么都没有」的返回值。若返回 null，每个调用点都要写判空，
         * 漏一处就是空指针；返回一个空对象，调用方用 hit() 判断即可。
         *
         * <p>执行步骤：
         * <ol>
         *     <li>① 直接构造一个 contextText 为空串、sources 为空列表的实例。
         *     用 List.of() 而不是 new ArrayList<>()，顺带获得「不可变」——
         *     谁也别想往这个共享的空结果里塞元素。</li>
         * </ol>
         *
         * <p>容易踩的坑：这里显式写 public 不能省。嵌套在接口里的 record 默认是 public，
         * 但 record 体内的成员仍是「不加修饰符即包级可见」，
         * 跨包的实现类调用它会编译失败——而失败只在编译期出现，运行时看不出问题。
         *
         * @return 空结果实例；每次调用都会新建一个，但内容恒定
         */
        public static RetrievalResult empty() {
            return new RetrievalResult("", List.of());
        }

        /**
         * 是否命中了资料
         *
         * <p>为什么这样设计：调用方只需要知道「有没有资料」，不需要自己判断
         * sources 是否为 null 或空。把这两种判断收在这里，调用点就只剩一个 if。
         *
         * <p>执行步骤：
         * <ol>
         *     <li>① 先判 null 再判空：record 是公开类型，外部完全可以构造出
         *     sources 为 null 的实例（绕过 empty()），这里多一个 null 判断成本极低。</li>
         * </ol>
         *
         * <p>容易踩的坑：不要用 contextText 是否为空来判断命中。
         * 资料文本理论上可能被拼成空串（虽然正常流程不会），而 sources 是权威依据。
         *
         * @return true 表示至少命中一条资料；false 表示没有命中
         */
        public boolean hit() {
            return sources != null && !sources.isEmpty();
        }
    }
}
