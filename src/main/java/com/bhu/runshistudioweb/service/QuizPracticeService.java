package com.bhu.runshistudioweb.service;

import com.baomidou.mybatisplus.extension.plugins.pagination.Page;
import com.baomidou.mybatisplus.spring.service.IService;
import com.bhu.runshistudioweb.model.dto.quiz.QuizAnswerRequest;
import com.bhu.runshistudioweb.model.dto.quiz.QuizBatchRequest;
import com.bhu.runshistudioweb.model.dto.quiz.QuizSkipRequest;
import com.bhu.runshistudioweb.model.entity.StudioQuizAnswer;
import com.bhu.runshistudioweb.model.vo.quiz.QuizBatchVO;
import com.bhu.runshistudioweb.model.vo.quiz.QuizOverviewVO;
import com.bhu.runshistudioweb.model.vo.quiz.QuizVerdictVO;

/**
 * 刷题服务（C 端：出题、判分、跳过、概览）
 *
 * <p>本接口是刷题模块对调用方的全部承诺，实现类只解释「为什么这么实现」。
 *
 * <p>准入规则：只有在队的工作室成员能用，判定权威是 studio_member 表
 * （ user_id 命中且 member_status=0），不是 sys_user.user_role。
 * 这与考勤模块完全同源：角色是权限标签，档案才是业务事实，两者可能不同步。
 * 非成员调用任意方法都抛 A0301，连教材列表都不给——他没有刷题资格，
 * 给了只会是一份空数据加一堆困惑。
 *
 * <p>判分在服务端，答案不下发：题目 VO 结构上没有 correctLabels / analysis
 * （见 QuizQuestionVO 的类注释），答案只在 submitAnswer 的返回值里出现。
 * 这是本模块的安全底线。注意它靠的是「目标类没有这个字段」，
 * 而不是「记得在转换时删掉」——后者只要有一处漏删就是事故，而且不会报错。
 *
 * <p>批次不落库：题目不含答案，整批交给前端持有即可；服务端只需要
 * batchId 做幂等（重复调用结果一致）。代价是换设备不能续答
 * （刷题不是考试，重开成本为 0），同设备刷新由前端 sessionStorage 兜住。
 *
 * <p>约定：参数不合法 / 业务不允许时抛 BusinessException，不返回 null。
 * 唯一的例外是最后三个方法：它们是内部工具方法，返回值语义在各自注释里写明。
 *
 * @author shaoshing
 */
public interface QuizPracticeService extends IService<StudioQuizAnswer> {

    /**
     * 开一批题目
     *
     * <p>为什么这样设计：三种模式的必填参数不同——顺序模式必须指定教材 + 章节，
     * 错题重刷与随机刷题都可以只给范围、甚至完全不给。这种「按模式决定必填性」的规则
     * 没法用 DTO 注解表达（注解是静态的，而必填性取决于另一个字段的取值），
     * 只能由实现校验，并且提示必须写清「哪个模式缺了哪个参数」——
     * 统一回一句「参数错误」会让用户不知道该补教材还是补章节。
     *
     * <p>批次 ID 由服务端生成，请求里没有这个字段：让前端传等于把
     * 「本轮是哪几题」的解释权交出去，前端就能伪造一个批次去重放别的题的判定。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 成员准入。必须排在任何查询之前：越权用户不该消耗哪怕一次数据库查询；</li>
     *     <li>② 校验模式取值。模式是闭集，非法值立刻报错而不是默认成某个模式，
     *     否则用户以为在刷错题、实际在刷顺序，而界面不会有任何异常提示；</li>
     *     <li>③ 归一化教材 / 章节名，并校验「选了章节就必须给教材」——
     *     只传章节无法定位是哪本书的哪一章；</li>
     *     <li>④ 收敛题量：null / 0 / 超大值都不该让请求失败，统一纠正到合法区间；</li>
     *     <li>⑤ 按模式分派取候选题目 ID，这是三种模式唯一分岔的地方；</li>
     *     <li>⑥ 候选为空时按模式给出不同提示：用户需要知道下一步该做什么，
     *     统一回一句「没有题目」等于什么都没说；</li>
     *     <li>⑦ 按 ID 批量取详情并按原顺序重排。批量查询不保证返回顺序，
     *     而顺序模式必须保持题序，这一步不能省；</li>
     *     <li>⑧ 题目可能在这几毫秒里被停用或删除，全部失效时按「无题」处理；</li>
     *     <li>⑨ 标记哪些题在错题本里——只给布尔标记，不带答案，也不带错题本条目 ID；</li>
     *     <li>⑩ 组装批次 VO 并生成批次 ID。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法<b>不幂等</b>——每调用一次就生成一个新的 batchId，
     * 相同的入参连调两次会得到两个不同的批次。这是刻意的（「再来一轮」就该是新的一轮），
     * 但调用方不能靠重试来「恢复」一个丢掉的批次。
     * 另一个坑是 total 取的是<b>组装后的真实条数</b>，不是请求里的 size：
     * 题量不足时两者不同，用 size 会让进度条永远走不满。
     *
     * @param request 开批请求，不能为 null（为 null 抛 A0401）；
     *                mode 必填，0-顺序、1-错题重刷、2-随机；
     *                顺序模式必须同时给教材与章节，其余模式可只给范围或完全不给；
     *                size 可为 null（用配置的默认题量），restart 为 null 时按 false 处理
     * @return 批次对象，含服务端生成的 batchId、模式、实际题量与题目列表；
     *         题目列表的结构里没有答案字段，调用方不必也无法做「删答案」处理
     * @throws com.bhu.runshistudioweb.exception.BusinessException 未登录（A0201）、
     *         非在队成员（A0301）、模式非法 / 只给章节没给教材（A0401）、
     *         本章已刷完 / 错题本为空 / 范围内无题（A0402）时抛出
     */
    QuizBatchVO startBatch(QuizBatchRequest request);

    /**
     * 提交作答（幂等）
     *
     * <p>为什么这样设计：判分必须在服务端，因为出题接口返回的题目 VO 里没有答案字段，
     * 前端拿不到正确答案，也无法自己算对错。这是「展示数据与判定数据物理分离」的落点——
     * 选项 JSON 只存标签与正文，正确答案单独存一列，出题接口的 VO 结构上就没有地方放答案。
     *
     * <p>幂等的实现：先 insert，撞唯一键 uk_user_batch_question（用户 + 批次 + 题目）时
     * 重读已有记录、原样返回首次判定——断网重试是移动端的常态，
     * 让用户看到「本题已作答」的红条比看到判定结果更糟。
     * 注意「幂等」在这里不只是「不报错」：重复提交时错题本的连对进度<b>也不会</b>再推进一次，
     * 否则用户双击一下就能白赚一次连对。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 成员准入 + 题目存在性校验。题目不存在直接报错，这是后续所有判断的前提；</li>
     *     <li>② 校验标签合法并规范化。顺序不能反：先归一的话非法字符会被静默丢掉，
     *     用户永远不知道自己传错了；</li>
     *     <li>③ 校验标签属于本题选项，防止「乱传标签刷判定」；</li>
     *     <li>④ 按题型校验标签数：单选传多个是非法请求（正常界面产生不了），
     *     多选只选一个是用户的真实选择，正常判错而不拒绝——这两种必须区分开；</li>
     *     <li>⑤ 判定。两侧都是「大写 + 去重 + 升序 + 无分隔」，因此集合相等就是字符串相等，
     *     一次 equals 即可，不必写集合运算；</li>
     *     <li>⑥ 先插作答记录。插入成功才说明「这次提交是有效的」，之后的错题本更新才有意义；
     *     撞唯一键说明是重复提交，转去读已有记录；</li>
     *     <li>⑦ 重复提交时按首次判定返回，且不更新错题本；</li>
     *     <li>⑧ 首次提交才更新错题本状态机。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法<b>不校验 questionId 是否属于 batchId</b>。服务端不持久化批次内容，
     * 因此无法校验。最坏影响是用户给自己刷出脏的作答记录，不涉及越权或他人数据。
     * 另一个坑是「已停用的题仍可提交」：批次已经发给用户了，此时拒绝会让他卡在
     * 一道永远答不了的题上——停用只应影响后续抽题与错题本展示。
     *
     * @param request 作答请求，不能为 null；batchId 与 questionId 必填且为正数；
     *                chosenLabels 允许带分隔符与小写，但不能含非法字符或重复标签
     * @return 判定结果，含本题的正确答案、解析、错题本动作与累计统计；
     *         重复提交时返回的是首次判定的快照，wrongBookAction 固定为 none；
     *         永不为 null，调用方不必判空
     * @throws com.bhu.runshistudioweb.exception.BusinessException 未登录（A0201）、
     *         非在队成员（A0301）、标签非法 / 未选 / 不属于本题选项 / 单选传多个（A0401）、
     *         题目不存在（A0402）时抛出
     */
    QuizVerdictVO submitAnswer(QuizAnswerRequest request);

    /**
     * 跳过题目（不返回答案、不写错题本）
     *
     * <p>为什么这样设计：跳过要单独落一条记录（result=跳过），而不是「什么都不做」。
     * 两个原因：一是断点续答需要区分「这题我处理过了（跳过）」与「还没轮到」，
     * 不记录的话用户刷新回来又会看到它；二是幂等需要依据——重复点跳过时靠唯一键
     * 判断「已经处理过」，直接返回成功即可。
     * 但响应里什么都不返回（只有布尔）——否则跳过按钮就成了看答案的捷径。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 成员准入 + 题目存在性校验。题目不存在时连记录都不该写，
     *     否则会留下一条指向不存在题目的作答记录；</li>
     *     <li>② 组装跳过记录：所选标签显式存 NULL 而不是空字符串——
     *     「没选」与「选了空」是两件事，存空串会让「跳过」与「提交了一个空答案」
     *     在数据上无法区分，统计时也会把空串当成一次真实作答；</li>
     *     <li>③ 插入并兜住唯一键冲突：冲突说明同一批同一题已经处理过（答过或跳过了），
     *     按幂等返回成功，不重复写；</li>
     *     <li>④ 恒返回 true：跳过这个动作只要记录落库（或本来就已经记录过）就算成功。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法刻意<b>不</b>推进错题本。跳过既不算答错也不算答对，
     * 若误把它接进状态机，会平白给错题本加一条记录、或推进连对进度——
     * 「跳过」就成了刷消解次数的漏洞。另外跳过记录计入「已处理」，
     * 但不计入正确率的分母（统计只认正确与错误）。
     *
     * @param request 跳过请求，不能为 null；batchId 与 questionId 必填且为正数
     * @return 恒为 true（重复跳过也返回 true）；失败只会以异常形式出现，
     *         调用方不必区分「这次写的」与「之前就有的」
     * @throws com.bhu.runshistudioweb.exception.BusinessException 未登录（A0201）、
     *         非在队成员（A0301）、题目不存在（A0402）、记录落库失败（B0002）时抛出
     */
    boolean skipQuestion(QuizSkipRequest request);

    /**
     * 学习概览（四个数字）
     *
     * <p>为什么这样设计：四个数字看起来要查四次，实际只需要三次——
     * 作答数与答对数由一条带 SUM(CASE WHEN) 的聚合查出（两个数字来自同一行，
     * 天然一致，不会出现「作答 100、答对 60」与「正确率 61%」对不上的情况），
     * 错题本的两个数由错题服务各查一次（它们各自带「题目是否可见」的过滤，
     * 无法与作答统计合并）。绝不写「四个指标四次查询」。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 成员准入，非成员不该看到任何统计数据；</li>
     *     <li>② 一次聚合拿到作答总数与答对数；</li>
     *     <li>③ 正确率按分母是否为 0 分两种：为 0 时给 null，避免把「没做过」
     *     显示成「全错」；</li>
     *     <li>④ 待复习数与已消解数分别来自错题服务，与错题本列表用同一套过滤条件，
     *     保证「概览数字」与「点进去看到的条数」一致。</li>
     * </ol>
     *
     * <p>容易踩的坑：正确率用 double 相除，必须先把分子转成 double，
     * 否则会先做整数除法得到 0 或 1，再转成 double 就只剩 0.0 与 1.0 两种结果。
     * 另一个反直觉点是 accuracy 允许为 null——前端必须对 null 显示「--」而不是 0%。
     *
     * @return 概览对象，永不为 null；从未作答时 answeredTotal 与 correctTotal 为 0、
     *         accuracy 为 null；错题本的两个数字在没有任何条目时为 0
     * @throws com.bhu.runshistudioweb.exception.BusinessException 未登录（A0201）、
     *         非在队成员（A0301）时抛出
     */
    QuizOverviewVO getOverview();

    /**
     * 校验当前登录用户是在队成员，并返回其账号 ID
     *
     * <p>为什么要把这个校验暴露出来：教材 / 章节树（ /quiz/catalog）的数据
     * 由 QuizQuestionService 提供，但准入规则属于本服务。
     * 如果 Controller 只挂 {@code @SaCheckLogin} 而不做成员校验，
     * 一个「只有账号、没有成员档案」的普通用户就能读到整个题库目录——
     * 数据本身不敏感，但这是准入规则的漏洞：他本不该进入这个模块的任何入口。
     *
     * <p>与其在 Controller 里复制一遍「查 studio_member 表」的逻辑（两份规则迟早漂移），
     * 不如把这个判定暴露成公开方法，让所有 /quiz/** 入口共用同一个实现。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 先判登录，未登录给 A0201；</li>
     *     <li>② 再查成员档案，查不到给 A0301。两步分开是为了让「未登录」与「不是成员」
     *     返回不同错误码——前者该去登录，后者该去找管理员；</li>
     *     <li>③ 返回账号 ID，供后续按用户维度查询。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法每次调用都会查一次成员表，且<b>不缓存</b>结果——
     * 成员状态可能在会话期间被管理员改动，缓存会让「刚被移出工作室的人还能继续刷题」。
     * 因此它只应在请求入口调用一次，把返回的 userId 往下传，不要放进循环。
     *
     * @return 当前登录账号 ID（用户 ID，不是成员档案 ID）
     * @throws com.bhu.runshistudioweb.exception.BusinessException 未登录（A0201）
     *         或非在队成员（A0301）时抛出
     */
    long requireActiveMemberId();

    /**
     * 我的累计作答与答对（供判分后即时回填，避免前端再调一次概览接口）
     *
     * <p>为什么这样设计：这两个数字总是一起用（概览与判定结果回填都要），
     * 拆成两个方法会让调用方查两次，而两次查询之间可能有新作答写入，
     * 于是「作答 100、答对 60」与算出来的正确率可能对不上。
     * 用一条聚合让两个数字来自同一行，天然一致。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 用一条 COUNT + SUM(CASE WHEN) 同时取两个数；</li>
     *     <li>② 结果类型限定为「正确」与「错误」：跳过不算作答，
     *     把它算进分母会让正确率虚低；</li>
     *     <li>③ 按列名取值时走 Number 接口，不硬转 Integer——
     *     COUNT 在部分驱动下返回 BigInteger，硬转只在特定环境炸。</li>
     * </ol>
     *
     * <p>容易踩的坑：本方法<b>不做成员校验</b>，它是纯统计工具，
     * 调用方必须自己先确认 userId 属于当前登录用户。若把它直接暴露成接口而不校验，
     * 任何人都能查到别人的刷题量。它出现在本接口上是为了让实现类之外也能调用，
     * 不代表它可以直接对外。
     *
     * @param userId 用户 ID；传错会统计到别人的数据，调用方负责传入当前登录用户
     * @return 长度 2 的数组：[累计作答数, 累计答对数]；没有作答记录时返回 {0, 0}，
     *         不会是 null，调用方不必判空但必须校验长度
     */
    int[] countAnsweredAndCorrect(long userId);

    /**
     * 分页查某用户在某批次的作答记录（供测试与排查使用）
     *
     * <p>为什么这样设计：批次本身不落库，服务端唯一知道「这一轮做了哪些题」的地方
     * 就是作答记录表。用户刷新页面或断网重连后，前端拿着 batchId 来查一次，
     * 就能知道哪些题已经处理过、分别是什么结果，从而把进度恢复到正确位置。
     * 排序按记录 ID 升序：作答记录是追加写的，ID 顺序即用户的操作顺序。
     *
     * <p>执行步骤：
     * <ol>
     *     <li>① 同时按用户与批次过滤。少用户条件会让别人拿到这一批的记录，
     *     少批次条件会混进其它轮次的记录；</li>
     *     <li>② 按 ID 升序排列，前端据此回放进度；</li>
     *     <li>③ 取第一页、页大小为上限值：一个批次的题量受配置封顶，一次取完即可。</li>
     * </ol>
     *
     * <p>容易踩的坑：返回的是<b>实体</b>而不是 VO，记录里含正确答案快照，
     * 因此本方法不能直接暴露成 C 端接口——真要对外必须先转成脱敏 VO。
     * 另外它不做成员校验，userId 由调用方保证是当前登录用户。
     *
     * @param userId 用户 ID，必须是当前登录用户
     * @param batchId 批次 ID；传一个不存在的批次不会报错，只会得到空页
     * @return 分页结果，按记录 ID 升序；没有记录时 records 为空列表（不是 null）
     */
    Page<StudioQuizAnswer> listByBatch(long userId, long batchId);
}
