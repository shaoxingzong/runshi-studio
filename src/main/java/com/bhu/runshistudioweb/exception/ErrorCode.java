package com.bhu.runshistudioweb.exception;

import lombok.Getter;

/**
 * 业务错误码枚举（遵循《阿里巴巴 Java 开发手册》错误码规范）
 *
 * author: shaoshing
 *
 * <p><b>为什么要从早期的 A0401 / B0001 改成现在这套</b>：
 * <ol>
 *     <li><b>错误码是 5 位字符串，不是数字。</b>数字型状态码会被顺手写成 HTTP 状态码
 *     （400/401/404/500）的补零形式，语义上混淆了「传输层」与「业务层」，也让前端自然地
 *     写出 {@code if (code)} 这种把 0 当假值的隐式依赖；</li>
 *     <li><b>第 1 位是「错误产生来源」。</b>{@code A} 用户端、{@code B} 当前系统、
 *     {@code C} 第三方服务——看到首字母就知道该找谁（见下表）；</li>
 *     <li><b>后 4 位是编号</b>，大类之间步长 100（A0200 登录、A0300 权限、A0400 参数……），
 *     三级细分在大类内 {@code +1}（A0301、A0302……）；</li>
 *     <li><b>全部正常返回 5 个零 {@code 00000}</b>——成功码同样占 5 位，
 *     避免有人误以为「没有 code 就是成功」。</li>
 * </ol>
 *
 * <p><b>ABC 三类的划分，以及各自的处置分工</b>：
 * <table border="1">
 *     <caption>错误产生来源</caption>
 *     <tr><th>首位</th><th>来源</th><th>本项目的场景</th><th>谁来处置</th></tr>
 *     <tr><td>{@code A}</td><td>用户端</td>
 *     <td>参数不合法、未登录、无权限、请求过频</td>
 *     <td>前端提示用户；<b>原样重试无意义</b></td></tr>
 *     <tr><td>{@code B}</td><td>当前系统</td>
 *     <td>未预期异常、业务操作失败（影响行数不符、切分结果为空）</td>
 *     <td>后端查日志；<b>重试可能成功</b></td></tr>
 *     <tr><td>{@code C}</td><td>第三方服务</td>
 *     <td>AI 对话 / 向量化服务不可用或超时</td>
 *     <td>等服务商恢复或降级；<b>不是本系统的 bug</b></td></tr>
 * </table>
 *
 * <p><b>新增错误码的三条纪律</b>：
 * <ul>
 *     <li>先定大类（属于 A / B / C 哪一端），再在大类内 {@code +1} 取号，不要跨类复用；</li>
 *     <li>不要往旧号段（4xxxx / 5xxxx）加新码，那是已废弃的 HTTP 风格号段；</li>
 *     <li>错误码<b>不体现版本号与错误等级</b>——等级由日志级别和告警策略表达，
 *     版本号会让调用方的判断逻辑随版本漂移。</li>
 * </ul>
 *
 * <p>注意：这里的 code 是「业务状态码」，不是 HTTP 状态码，接口的 HTTP 状态一律是 200。
 * 前端拦截器只依赖它做分支判断（见 {@code web/src/api/request.ts}）。
 */
@Getter
public enum ErrorCode {

    // ==================== 成功 ====================

    /** 成功（手册规定：全部正常、但不得不填充错误码时返回五个零） */
    SUCCESS("00000", "ok"),

    // ==================== A 类：错误来源于用户 ====================

    /** A0200 用户登录异常：未携带凭证、凭证失效/被篡改、被顶下线 */
    NOT_LOGIN_ERROR("A0201", "未登录"),

    /** A0300 访问权限问题：已登录但角色不足（如普通成员访问管理员接口） */
    NO_AUTH_ERROR("A0301", "无权限"),

    /**
     * A0300 访问权限问题：账号被封禁
     *
     * <p>与「无权限」的区别：无权限是<b>角色不够</b>（换个有权限的账号即可），
     * 封禁是<b>账号本身被限制</b>（换账号也没用，只能联系管理员），
     * 前端对两者的处理分别是「跳登录页」与「提示联系管理员」。
     */
    FORBIDDEN_ERROR("A0302", "禁止访问"),

    /** A0400 用户请求参数错误：必填项缺失、格式不合法、超出长度或范围 */
    PARAMS_ERROR("A0401", "请求参数错误"),

    /** A0400 用户请求参数错误：按 ID 查询无结果、关联数据已被删除（即请求了不存在的资源） */
    NOT_FOUND_ERROR("A0402", "请求数据不存在"),

    /** A0500 用户请求服务异常：请求次数超出限制（见 manager/AiRateLimitManager） */
    TOO_MANY_REQUESTS_ERROR("A0501", "请求过于频繁"),

    // ==================== B 类：错误来源于当前系统 ====================

    /** B0001 系统执行出错：未预期异常的统一兜底，对外只提示「系统错误」，细节只进日志 */
    SYSTEM_ERROR("B0001", "系统内部异常"),

    /**
     * B0002 业务操作失败：更新影响行数不为 1、切分结果为空等「预期内但不成功」
     *
     * <p>与 {@link #SYSTEM_ERROR} 的边界：本类是<b>业务上明确的不成功</b>（可预期、可解释），
     * 兜底的 B0001 是<b>没预料到的异常</b>。两者都要查后端，但排查方向不同。
     */
    OPERATION_ERROR("B0002", "操作失败"),

    // ==================== C 类：错误来源于第三方服务 ====================

    /**
     * C0200 第三方系统执行超时 / 不可用：AI 对话与向量化服务（阿里云百炼等 OpenAI 兼容服务）
     *
     * <p><b>为什么它必须独立成 C 类</b>：AI 服务是<b>外部依赖</b>，它挂了不是本系统的 bug。
     * 归到 B 类会造成两个后果——
     * ① 告警把「服务商故障」算成「本系统故障」，污染可用性指标；
     * ② 排查时先翻自己的日志，方向被带偏。独立成 C 类后，
     * 重试策略（等对方恢复 vs 改代码）与告警对象（服务商 vs 自己）都能分开。
     */
    AI_SERVICE_ERROR("C0200", "AI 服务暂时不可用");

    /** 状态码：5 位字符串 = 来源（A/B/C）+ 4 位编号 */
    private final String code;

    /** 默认提示信息，可被 {@code ResultUtils.error(errorCode, message)} 覆盖 */
    private final String message;

    /**
     * 枚举构造器（枚举的构造器天然是 private，外部无法 new，保证全局唯一）
     *
     * @param code    状态码（5 位：来源 + 4 位编号）
     * @param message 默认提示信息
     */
    ErrorCode(String code, String message) {
        this.code = code;
        this.message = message;
    }
}
